#!/usr/bin/env bash
# ONE installed copy of the git guard hooks, outside every checkout.
#
#   bash scripts/hooks_central.sh install [repo ...]   # build $FSR_HOOKS_DIR from root's REMOTE main,
#                                                      # point every repo's core.hooksPath at it
#   bash scripts/hooks_central.sh check   [repo ...]   # rc 0 only when the installed copy is root
#                                                      # main's and every repo points at it
#
# Why: repos used to point into the shared root checkout (scripts/githooks), so
# the guard that ran was whatever branch another session had out (the slow
# guard kept running after the fast one was on main), and the framework and
# connector carried per-repo copies that went stale. Now there is one dir,
# installed from a named commit of root main, and a check that fails when it
# lags main or when any repo points elsewhere.
#
# $FSR_HOOKS_DIR (default ~/.local/share/fsr-hooks) holds:
#   reference-transaction   the main guard, from <root main>:scripts/githooks
#   <name> for every other hook git runs: a generic shim. With no recorded
#     fsr.guardOriginalHooksPath it runs the global hook, then <common>/hooks;
#     with one (the connector: scripts/hooks) it runs that repo's own hook.
#   .installed-from         the root commit it was built from
#
# Repos (default): the root main checkout, every widgets-src/* repo, the
# framework and the connector (scripts/repo_paths.sh).
set -euo pipefail

# FSR_ROOT_DIR: the root repo when this script runs from a copy (promote runs
# root main's copy from a temp file).
HERE="${FSR_ROOT_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
ROOT_MAIN="$(dirname "$(git -C "$HERE" rev-parse --path-format=absolute --git-common-dir)")"
DIR="${FSR_HOOKS_DIR:-$HOME/.local/share/fsr-hooks}"
HOOK_NAMES=(pre-commit pre-push commit-msg prepare-commit-msg post-merge post-checkout)

die() { echo "hooks: $*" >&2; exit 1; }

default_repos() {
    echo "$ROOT_MAIN"
    local d
    for d in "$ROOT_MAIN"/widgets-src/*/; do [[ -e "$d/.git" ]] && echo "${d%/}"; done
    bash "$ROOT_MAIN/scripts/repo_paths.sh" framework 2>/dev/null || true
    bash "$ROOT_MAIN/scripts/repo_paths.sh" conn 2>/dev/null || true
}

root_main_sha() {
    local rem
    rem="$(git -C "$ROOT_MAIN" for-each-ref --format='%(upstream:remotename)' refs/heads/main)"
    git -C "$ROOT_MAIN" rev-parse "refs/remotes/${rem:-origin}/main"
}

write_shim() {  # $1 file
    cat > "$1" <<'SHIM'
#!/usr/bin/env bash
# Generated by fsr_all_widgets scripts/hooks_central.sh. Do not edit.
[ -n "${FSR_HOOK_SHIM:-}" ] && exit 0   # invoked back by the global hook: it already ran
name="$(basename "$0")"
input=""; [ -t 0 ] || input="$(cat)"
common="$(git rev-parse --git-common-dir 2>/dev/null)"; common="$(cd "$common" 2>/dev/null && pwd)"
orig="$(git config --local --get fsr.guardOriginalHooksPath 2>/dev/null || true)"
run() { if [ -n "$input" ]; then printf '%s\n' "$input" | "$@"; else "$@"; fi; }
if [ -z "$orig" ]; then
  global="$(git config --global core.hooksPath 2>/dev/null || true)"; global="${global/#\~/$HOME}"
  if [ -n "$global" ] && [ -x "$global/$name" ]; then
    FSR_HOOK_SHIM=1 run "$global/$name" "$@" || exit $?
  fi
  repo_hook="$common/hooks/$name"
else
  case "$orig" in
    /*) repo_hook="$orig/$name" ;;
    *)  top="$(git rev-parse --show-toplevel 2>/dev/null)" || exit 0; repo_hook="$top/$orig/$name" ;;
  esac
fi
[ -x "$repo_hook" ] || exit 0
run "$repo_hook" "$@"
SHIM
    chmod +x "$1"
}

# A hooksPath this tooling owns (old or new): not the repo's own hooks.
ours() {
    case "$1" in
        "") return 0 ;;
        "$DIR") return 0 ;;
        */scripts/githooks|*/fsr-guard-hooks) return 0 ;;
    esac
    return 1
}

cmd_install() {
    local sha tmp r cur
    sha="$(root_main_sha)" || die "cannot resolve root's remote main"
    tmp="$(mktemp -d "${DIR%/*}/.fsr-hooks.XXXXXX" 2>/dev/null || { mkdir -p "${DIR%/*}"; mktemp -d "${DIR%/*}/.fsr-hooks.XXXXXX"; })"
    git -C "$ROOT_MAIN" show "$sha:scripts/githooks/reference-transaction" > "$tmp/reference-transaction" \
        || { rm -rf "$tmp"; die "root main $sha has no scripts/githooks/reference-transaction"; }
    chmod +x "$tmp/reference-transaction"
    for r in "${HOOK_NAMES[@]}"; do write_shim "$tmp/$r"; done
    echo "$sha" > "$tmp/.installed-from"
    # Swap in whole: a hook never sees a half-written dir.
    rm -rf "$DIR.old"; [[ -d "$DIR" ]] && mv "$DIR" "$DIR.old"; mv "$tmp" "$DIR"; rm -rf "$DIR.old"
    (( $# )) || { mapfile -t _r < <(default_repos); set -- "${_r[@]}"; }
    local n=$#
    for r in "$@"; do
        [[ -e "$r/.git" ]] || { echo "hooks: skip $r (not a repo)"; continue; }
        cur="$(git -C "$r" config --local --get core.hooksPath || true)"
        # Keep a repo's OWN hooks dir (connector: scripts/hooks) as the one the shim chains to.
        if ! ours "$cur"; then git -C "$r" config --local fsr.guardOriginalHooksPath "$cur"; fi
        git -C "$r" config --local core.hooksPath "$DIR"
    done
    echo "hooks: $DIR from root main ${sha:0:9}; $n repo(s) point at it"
}

cmd_check() {
    local bad=0 want have r cur
    want="$(root_main_sha 2>/dev/null || true)"
    have="$(cat "$DIR/.installed-from" 2>/dev/null || true)"
    if [[ -z "$have" ]]; then echo "FAIL hooks: nothing installed at $DIR (run: bash scripts/hooks_central.sh install)" >&2; bad=1
    elif [[ "$have" != "$want" ]] && ! cmp -s <(git -C "$ROOT_MAIN" show "$have:scripts/githooks/reference-transaction" 2>/dev/null) \
                                         <(git -C "$ROOT_MAIN" show "$want:scripts/githooks/reference-transaction" 2>/dev/null); then
        # Another root commit is fine when the guard is byte-identical; a changed guard is not.
        echo "FAIL hooks: installed from ${have:0:9}, root main is ${want:0:9} and the guard differs (run install)" >&2; bad=1
    fi
    (( $# )) || { mapfile -t _r < <(default_repos); set -- "${_r[@]}"; }
    for r in "$@"; do
        [[ -e "$r/.git" ]] || continue
        cur="$(git -C "$r" config --local --get core.hooksPath || true)"
        [[ "$cur" == "$DIR" ]] || { echo "FAIL hooks: $r core.hooksPath='${cur}' (want $DIR)" >&2; bad=1; }
    done
    (( bad )) || echo "hooks: OK ($DIR @ ${have:0:9})"
    return $bad
}

case "${1:-}" in
    install|check) c="$1"; shift; "cmd_$c" "$@" ;;
    *) sed -n '2,8p' "$0" >&2; exit 2 ;;
esac
