#!/usr/bin/env bash
# Point each given repo (default: this repo + every widgets-src/* repo) at
# scripts/githooks via a repo-local core.hooksPath. The shims there chain to the
# global hooks, so the en/em-dash pre-commit keeps running. Run by make setup.
# Usage: scripts/install-git-hooks.sh [repo ...]
#
# Repos that have their OWN hooks (framework: global hooks + .git/hooks; connector:
# scripts/hooks) are not pointed at scripts/githooks. Install the main guard
# there with --chain, which keeps every existing hook running:
#   scripts/install-git-hooks.sh --chain <repo> [<repo> ...]
# It writes <git-common-dir>/fsr-guard-hooks/ (a copy of reference-transaction plus
# generated shims for the other hooks), records the previous core.hooksPath in
# git config fsr.guardOriginalHooksPath, then points core.hooksPath at the guard
# dir. Re-run to refresh the copy or after `make hooks` in the connector resets
# core.hooksPath. Works for bare repos and for repos with extra worktrees.
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
hooks="$root/scripts/githooks"
# A worktree of this repo is not the stable path; prefer the main checkout.
common="$(cd "$root" && cd "$(git rev-parse --git-common-dir)" && pwd)"
[ "$(basename "$common")" = .git ] && [ -d "$(dirname "$common")/scripts/githooks" ] && hooks="$(dirname "$common")/scripts/githooks"

if [ "${1:-}" = --chain ]; then
  shift
  [ "$#" -gt 0 ] || { echo "usage: $0 --chain <repo> [<repo> ...]" >&2; exit 2; }
  src="$root/scripts/githooks/reference-transaction"
  for r in "$@"; do
    rc="$(cd "$r" && cd "$(git rev-parse --git-common-dir)" && pwd)"
    guard="$rc/fsr-guard-hooks"
    cur="$(git -C "$r" config --local --get core.hooksPath || true)"
    if [ "$cur" != "$guard" ]; then   # first install (or a reset by another installer)
      git -C "$r" config --local fsr.guardOriginalHooksPath "$cur"
    fi
    mkdir -p "$guard"
    cp "$src" "$guard/reference-transaction"; chmod +x "$guard/reference-transaction"
    # Generic shim: run the global hook only when no repo-local hooksPath was in
    # effect (then the global dir was the active one); then run the repo's own hook
    # (original local hooksPath, relative ones against the worktree root, else
    # <common>/hooks). stdin is buffered so both see the pre-push ref list.
    for name in pre-commit pre-push commit-msg prepare-commit-msg post-merge post-checkout; do
      cat > "$guard/$name" <<'SHIM'
#!/usr/bin/env bash
# Generated by fsr_all_widgets scripts/install-git-hooks.sh --chain. Do not edit.
[ -n "${FSR_HOOK_SHIM:-}" ] && exit 0   # invoked back by the global hook: it already ran, we run the repo hook
name="$(basename "$0")"
input=""; [ -t 0 ] || input="$(cat)"
common="$(git rev-parse --git-common-dir 2>/dev/null)"; common="$(cd "$common" 2>/dev/null && pwd)"
orig="$(git config --local --get fsr.guardOriginalHooksPath 2>/dev/null || true)"
run() { if [ -n "$input" ]; then printf '%s\n' "$input" | "$@"; else "$@"; fi; }
if [ -z "$orig" ]; then
  global="$(git config --global core.hooksPath 2>/dev/null || true)"; global="${global/#\~/$HOME}"
  if [ -n "$global" ] && [ -x "$global/$name" ] && [ -z "${FSR_HOOK_SHIM:-}" ]; then
    FSR_HOOK_SHIM=1 run "$global/$name" "$@" || exit $?
  fi
  repo_hook="$common/hooks/$name"
else
  case "$orig" in
    /*) repo_hook="$orig/$name" ;;
    *)  top="$(git rev-parse --show-toplevel 2>/dev/null)" || exit 0; repo_hook="$top/$orig/$name" ;;
  esac
fi
[ -x "$repo_hook" ] || exit 0
run "$repo_hook" "$@"
SHIM
      chmod +x "$guard/$name"
    done
    git -C "$r" config --local core.hooksPath "$guard"
    echo "git guard: $r -> $guard (was: ${cur:-<global/.git hooks>})"
  done
  exit 0
fi

if [ "$#" -eq 0 ]; then set -- "$root"; for d in "$root"/widgets-src/*/; do [ -e "$d/.git" ] && set -- "$@" "${d%/}"; done; fi
for r in "$@"; do
  git -C "$r" config core.hooksPath "$hooks" && echo "git hooks: $r -> $hooks"
done
